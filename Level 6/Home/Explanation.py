"""
5) კომეტარებით ახსენით თუ რა განსხვავებაა /, //, და % მათემატიკურ ოპერატორებს შორის, დაწერეთ რას აკეთებს თითოეული
"""


# / - ჩვეულებრივი გაყოფა (პასუხი ყოველთვის ათწილადია)
print(10 / 3)  # 3.3333...

# // - მთელი გაყოფა (აგდებს წერტილის მერე ციფრებს)
print(10 // 3) # 3

# % - ნაშთი (რა რჩება გაყოფის მერე ზედმეტი)
print(10 % 3)  # 1
